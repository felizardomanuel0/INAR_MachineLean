def obter_descricao_portugues(doenca_ingles: str) -> str:
    """
    Obtém a descrição em português de uma doença
    
    Args:
        doenca_ingles (str): Nome da doença em inglês
        
    Returns:
        str: Descrição em português ou string vazia se não encontrada
    """
    return DESCRICOES_DOENCAS_PORTUGUES.get(doenca_ingles.strip(), "")

def traduzir_descricao_se_necessario(descricao: str, nome_doenca: str) -> str:
    """
    Verifica se a descrição precisa ser traduzida e retorna a versão em português
    
    Args:
        descricao (str): Descrição atual (pode estar em inglês)
        nome_doenca (str): Nome da doença para buscar tradução
        
    Returns:
        str: Descrição em português
    """
    # Tentar buscar tradução com o nome exato
    nome_limpo = nome_doenca.strip()
    descricao_pt = DESCRICOES_DOENCAS_PORTUGUES.get(nome_limpo, "")
    if descricao_pt:
        return descricao_pt
    
    # Tentar buscar em minúsculas
    descricao_pt = DESCRICOES_DOENCAS_PORTUGUES.get(nome_limpo.lower(), "")
    if descricao_pt:
        return descricao_pt
    
    # Tentar buscar com primeira letra maiúscula
    nome_capitalized = nome_limpo.capitalize()
    descricao_pt = DESCRICOES_DOENCAS_PORTUGUES.get(nome_capitalized, "")
    if descricao_pt:
        return descricao_pt
    
    # Busca parcial por chaves que contêm partes do nome
    for chave, traducao in DESCRICOES_DOENCAS_PORTUGUES.items():
        if nome_limpo.lower() in chave.lower() or chave.lower() in nome_limpo.lower():
            return traducao
    
    # Se não encontrou tradução, retorna a descrição original
    return descricao