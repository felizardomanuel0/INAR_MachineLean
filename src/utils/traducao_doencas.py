# Dicionário reverso (português para inglês)
TRADUCAO_DOENCAS_REVERSO = {v: k for k, v in TRADUCAO_DOENCAS.items()}

def traduzir_doenca_para_portugues(doenca_ingles: str) -> str:
    """Traduz nome da doença do inglês para português"""
    return TRADUCAO_DOENCAS.get(doenca_ingles, doenca_ingles)

def traduzir_doenca_para_ingles(doenca_portugues: str) -> str:
    """Traduz nome da doença do português para inglês"""
    return TRADUCAO_DOENCAS_REVERSO.get(doenca_portugues, doenca_portugues)

def obter_todas_doencas_portugues() -> list:
    """Retorna lista de todas as doenças em português"""
    return list(TRADUCAO_DOENCAS.values())

def obter_todas_doencas_ingles() -> list:
    """Retorna lista de todas as doenças em inglês"""
    return list(TRADUCAO_DOENCAS.keys())